#!/usr/bin/env node
/**
 * Turn the URL ledger's dispositions into Netlify redirect rules.
 *
 * wp-migration M-REDIRECT-WIRED: an extracted redirect file that is not wired
 * to the host layer is a note, not a migration step. This writes
 * dist/_redirects, which Netlify reads directly, so the rules ship with the
 * build rather than sitting in a data file nobody connected.
 *
 * Runs as part of `npm run build`, after `astro build`.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const P = (...p) => join(ROOT, ...p);

const rows = readFileSync(P("docs/url-ledger.csv"), "utf8").trim().split("\n").slice(1);
const parse = (line) => {
  const out = [];
  let cur = "";
  let q = false;
  for (const ch of line) {
    if (ch === '"') q = !q;
    else if (ch === "," && !q) {
      out.push(cur);
      cur = "";
    }
    else cur += ch;
  }
  out.push(cur);
  return out;
};

const rules = [];
const seen = new Set();
for (const line of rows) {
  const c = parse(line);
  const [path, , , , , , , , , , , disposition, target] = c;
  if (!path || disposition === "keep" || !target || path === target) continue;
  if (seen.has(path)) continue;
  seen.add(path);
  rules.push(`${path} ${target} 301!`);
}

// WordPress endpoints that no longer exist but stay in crawlers' caches.
const wpCruft = [
  "/feed/ / 301",
  "/comments/feed/ / 301",
  "/wp-json/* / 301",
  "/wp-admin/* / 301",
  "/wp-login.php / 301",
  "/xmlrpc.php / 301",
  "/author/* / 301",
  "/category/* / 301",
];

const body = [
  "# Generated by scripts/generate-redirects.mjs from docs/url-ledger.csv.",
  "# Do not edit by hand: `npm run build` overwrites this file.",
  "",
  "# Pages whose URL changed in the migration.",
  ...rules,
  "",
  "# WordPress endpoints that no longer exist.",
  ...wpCruft,
  "",
].join("\n");

const out = P("dist/_redirects");
if (!existsSync(P("dist"))) {
  console.error("dist/ not found - run `astro build` first.");
  process.exitCode = 1;
} else {
  writeFileSync(out, body);
  console.log(`redirects written: ${rules.length} page rules + ${wpCruft.length} WordPress endpoints`);
}
